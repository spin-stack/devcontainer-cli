// fakeTestContainers replaces the runner's `up` and `exec` for one test: start
// answers each project with check(workspace) and the id "cid" (or startErr),
// and a script passes when pass says so.
func fakeTestContainers(t *testing.T, startErr error, check func(ws string), pass func(script, ws string) bool) {
	t.Helper()
	oldStart, oldRun := startTestContainer, runTestScript
	t.Cleanup(func() { startTestContainer, runTestScript = oldStart, oldRun })
	startTestContainer = func(ws string, _ bool, _ []string) (string, error) {
		if check != nil {
			check(ws)
		}
		if startErr != nil {
			return "", startErr
		}
		return "cid", nil
	}
	runTestScript = func(id, script, ws string) bool {
		if id != "cid" {
			t.Errorf("script %s ran in container %q, want the started one", script, id)
		}
		if !pfs.IsFile(filepath.Join(ws, "dev-container-features-test-lib")) {
			t.Errorf("script %s ran without the test library in %s", script, ws)
		}
		return pass(script, ws)
	}
}

func readConfig(t *testing.T, ws string) map[string]any {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(ws, ".devcontainer", "devcontainer.json"))
	if err != nil {
		t.Fatal(err)
	}
	var cfg map[string]any
	if err := json.Unmarshal(data, &cfg); err != nil {
		t.Fatalf("generated devcontainer.json does not parse: %v\n%s", err, data)
	}
	return cfg
}

func TestAutoTestConfig(t *testing.T) {
	want := "{\n\t\"remoteUser\": \"vscode\",\n\t\"image\": \"alpine\",\n\t\"features\": {\n\t\t\"./a\": {},\n\t\t\"./b\": {}\n\t}\n}"
	if got := autoTestConfig([]string{"a", "b"}, "alpine", "vscode"); got != want {
		t.Errorf("config = %q, want %q", got, want)
	}
	want = "{\n\t\n\t\"image\": \"alpine\",\n\t\"features\": {\n\t\t\"./a\": {}\n\t}\n}"
	if got := autoTestConfig([]string{"a"}, "alpine", ""); got != want {
		t.Errorf("config without remote user = %q, want %q", got, want)
	}
}

func TestContainerIDFromUpOutput(t *testing.T) {
	if id, err := containerIDFromUpOutput([]byte(`{"outcome":"success","containerId":"abc"}`)); err != nil || id != "abc" {
		t.Errorf("success: id = %q, err = %v", id, err)
	}
	if _, err := containerIDFromUpOutput([]byte(`{"outcome":"error","description":"boom"}`)); err == nil || err.Error() != "up failed: boom" {
		t.Errorf("failure: err = %v", err)
	}
	if _, err := containerIDFromUpOutput([]byte(`not json`)); err == nil {
		t.Error("garbage: want a parse error")
	}
}

// The autogenerated project stages every Feature and its config, then each
// Feature's test.sh runs in the one container: passed, failed, or skipped when
// there is no test.sh.
func TestRunAutoTestsRunsEachFeatureTest(t *testing.T) {
	base := t.TempDir()
	for _, f := range []string{"pass", "fail", "untested"} {
		writeFile(t, filepath.Join(base, "src", f, "install.sh"), "#!/bin/sh\n", 0o755)
	}
	writeFile(t, filepath.Join(base, "test", "pass", "test.sh"), "true\n", 0o755)
	writeFile(t, filepath.Join(base, "test", "fail", "test.sh"), "false\n", 0o755)
	fakeTestContainers(t, nil, func(ws string) {
		cfg := readConfig(t, ws)
		if cfg["image"] != "alpine" || len(cfg["features"].(map[string]any)) != 3 {
			t.Errorf("config = %v", cfg)
		}
		if !pfs.IsFile(filepath.Join(ws, ".devcontainer", "pass", "install.sh")) {
			t.Error("feature not staged next to the config")
		}
	}, func(script, ws string) bool {
		if !pfs.IsFile(filepath.Join(ws, script)) {
			t.Errorf("test script %s not copied into the workspace", script)
		}
		return script == "pass/test.sh"
	})

	got := runAutoTests(log.Null, base, []string{"pass", "fail", "untested"}, "alpine", "", true, nil)
	want := []testResult{
		{Name: "pass", Status: testPassed},
		{Name: "fail", Status: testFailed},
		{Name: "untested", Status: testSkipped, Detail: "test.sh not found"},
	}
	if len(got) != len(want) {
		t.Fatalf("results = %+v, want %+v", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("result %d = %+v, want %+v", i, got[i], want[i])
		}
	}
}

func TestRunAutoTestsReportsContainerFailure(t *testing.T) {
	base := t.TempDir()
	writeFile(t, filepath.Join(base, "src", "a", "install.sh"), "#!/bin/sh\n", 0o755)
	writeFile(t, filepath.Join(base, "test", "a", "test.sh"), "true\n", 0o755)
	fakeTestContainers(t, errors.New("up failed: boom"), nil, func(string, string) bool {
		t.Error("a script ran without a container")
		return true
	})
	got := runAutoTests(log.Null, base, []string{"a"}, "alpine", "", true, nil)
	if len(got) != 1 || got[0] != (testResult{Name: "autogenerated setup", Status: testError, Detail: "up failed: boom"}) {
		t.Errorf("results = %+v", got)
	}
}

// Scenarios matching --filter run in their own project: local Features are
// staged and referenced as "./<id>", others kept as given; a scenario whose
// config is not an object, or whose container does not start, is an error.
func TestRunScenarioTestsRunsFilteredScenarios(t *testing.T) {
	base := t.TempDir()
	writeFile(t, filepath.Join(base, "src", "color", "install.sh"), "#!/bin/sh\n", 0o755)
	testDir := filepath.Join(base, "test", "color")
	writeFile(t, filepath.Join(testDir, "scenarios.json"), `{
		"keep_one": {"image": "alpine", "features": {"color": {"favorite": "red"}, "ghcr.io/x/y/z:1": {}}},
		"keep_bad": ["not", "an", "object"],
		"other": {"image": "alpine"}
	}`, 0o644)
	for _, s := range []string{"keep_one", "keep_bad", "other"} {
		writeFile(t, filepath.Join(testDir, s+".sh"), "true\n", 0o755)
	}
	fakeTestContainers(t, nil, func(ws string) {
		feats, _ := readConfig(t, ws)["features"].(map[string]any)
		if _, ok := feats["./color"]; !ok || feats["ghcr.io/x/y/z:1"] == nil || len(feats) != 2 {
			t.Errorf("features = %v, want ./color and the OCI one", feats)
		}
		if !pfs.IsFile(filepath.Join(ws, ".devcontainer", "color", "install.sh")) {
			t.Error("local feature not staged")
		}
	}, func(script, ws string) bool {
		if script != "color/keep_one.sh" || !pfs.IsFile(filepath.Join(ws, script)) {
			t.Errorf("ran %s, want color/keep_one.sh copied into the workspace", script)
		}
		return true
	})

	got := map[string]testResult{}
	for _, r := range runScenarioTests(log.Null, base, testDir, "color", "keep", "alpine", "", true, nil) {
		got[r.Name] = r
	}
	if len(got) != 2 || got["keep_one"].Status != testPassed || got["keep_bad"].Status != testError {
		t.Errorf("results = %+v, want keep_one passed and keep_bad an error", got)
	}
}

func TestRunScenarioTestsReportsContainerFailure(t *testing.T) {
	base := t.TempDir()
	testDir := filepath.Join(base, "test", "x")
	writeFile(t, filepath.Join(testDir, "scenarios.json"), `{"s": {"image": "alpine"}}`, 0o644)
	writeFile(t, filepath.Join(testDir, "s.sh"), "true\n", 0o755)
	fakeTestContainers(t, errors.New("up failed: boom"), nil, func(string, string) bool {
		t.Error("a script ran without a container")
		return true
	})
	got := runScenarioTests(log.Null, base, testDir, "x", "", "alpine", "", true, nil)
	if len(got) != 1 || got[0] != (testResult{Name: "s", Status: testError, Detail: "up failed: boom"}) {
		t.Errorf("results = %+v", got)
	}
}
